			-0.1196, 1.6895, 0.6067, 1.5485;

	inputs[1] << -0.7046, 1.7230, -0.9191, 0.0907, 0.1982, 0.1191, -1.5407, -0.6223,
			-0.9332, 0.2344, 1.0988, -0.5010, 1.8643, 0.6191, 0.5553, -0.6095,
			-1.8960, -1.5768, 0.1600, -0.3005, -0.0142, -0.5990, 0.1091, 2.2013,
			0.9058, 0.1865, 0.2177, -0.5360, -0.9588, 0.6640, 1.2153, -1.3619,
			0.0482, 1.0783, -0.0540, -1.1351;

