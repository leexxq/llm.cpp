#include <attention.h>
#include <gtest/gtest.h>

class TestAttention : public testing::Test {
protected:
	using VecBT3C = VecBTC;
	Attention attention;
};

TEST_F(TestAttention, forward1) {
	attention = Attention{ 2, 3, 4, 2 };

	VecBT3C input(2, Matf(3, 3 * 4)); // (2 , 3 , 3 * 4 )
	input[0] << 0.8373, 0.5131, 0.3924, -0.2656, -1.3626, 0.1335, 0.2221, 1.7884,
			2.6642, 0.0967, 0.6510, -2.0046, -0.1256, 0.2871, 1.3851, -0.5032,
			0.9438, -0.1079, 0.1583, 0.6254, 0.0904, -0.9528, -1.6632, -0.6742,
			-1.2677, -1.7125, 1.0614, -1.0930, -0.9684, -1.2489, 1.4263, 1.4226,
			-0.1196, 1.6895, 0.6067, 1.5485;
	input[1] << -0.7046, 1.7230, -0.9191, 0.0907, 0.1982, 0.1191, -1.5407, -0.6223,
			-0.9332, 0.2344, 1.0988, -0.5010, 1.8643, 0.6191, 0.5553, -0.6095,
			-1.8960, -1.5768, 0.1600, -0.3005, -0.0142, -0.5990, 0.1091, 2.2013,
			0.9058, 0.1865, 0.2177, -0.5360, -0.9588, 0.6640, 1.2153, -1.3619,
			0.0482, 1.0783, -0.0540, -1.1351;

	VecBTC resexp(2, Matf(3, 4));

	resexp[0] << 0.5411, -0.3793, -0.1275, -0.1377,
			1.0567, 0.2354, 0.0874, 0.4528,
			0.4540, 1.2743, -0.1899, 0.2250;

	resexp[1] << -0.1602, 0.7779, 0.7529, 0.0418,
			-0.7045, 0.3936, 0.1576, -0.2030,
			-0.5296, 0.3842, 0.2672, -0.0636;

	VecBTC res = attention.Forward(input);

	for (int b = 0; b < 2; ++b) {
		EXPECT_TRUE(res[b].isApprox(resexp[b],0.001));
	}
}
